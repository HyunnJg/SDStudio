// Synthetic offline library probe: real renderer/preload/store; no account/token/file path import.
const assert = require('node:assert/strict');
const { BrowserWindow } = require('electron');
module.exports = async ({ contents, evaluate, click, fill, until, checks }) => {
  const initialEntries = (await evaluate('window.electron.promptLibrary.read()')).value.entries.length;
  const beforeProjects = (await evaluate('window.electron.projects.list()')).value.map(p => [p.id, p.revision]);
  const before = await evaluate("[document.querySelector('#live-prompt').value,document.querySelector('#live-negative').value,document.querySelector('#live-quality').value,document.querySelector('#live-uc-preset').value]");
  const select = (selector, value) => evaluate(`(()=>{const input=document.querySelector(${JSON.stringify(selector)});input.value=${JSON.stringify(value)};input.dispatchEvent(new Event('change',{bubbles:true}));})()`);
  const waitReady = () => until(() => evaluate("!!document.querySelector('[data-testid=prompt-library]')?.open && !document.querySelector('[data-testid=prompt-library] fieldset').disabled"));
  const close = async () => { await click('[data-testid=library-close]'); await until(() => evaluate("!document.querySelector('[data-testid=prompt-library]')")); };
  await click('[data-testid=main-preset]'); await waitReady();
  await fill('[data-testid=library-name]', 'Synthetic library main');
  await fill('[data-testid=library-prompt]', 'synthetic reusable garden');
  await fill('[data-testid=library-negative]', 'synthetic blur');
  await select('.library-preset-settings select', 'none');
  await select('.library-preset-settings label:last-child select', 'none');
  await click('[data-testid=library-save]');
  await until(async () => (await evaluate('window.electron.promptLibrary.read()')).value.entries.length === initialEntries + 1);
  await waitReady();
  assert.equal(await evaluate("document.querySelector('#live-prompt').value"), before[0]);
  assert.ok((await evaluate("document.querySelector('[data-testid=library-save-state]').textContent")).includes('저장됨'));
  await click('[data-testid=library-apply]');
  await until(() => evaluate("document.querySelector('#live-prompt').value==='synthetic reusable garden'"));
  assert.ok((await evaluate("document.querySelector('[data-testid=applied-main-preset]').textContent")).includes('Synthetic library main'));
  assert.equal(await evaluate("document.querySelector('[data-testid=generation-status]').textContent"), '');
  assert.deepEqual(await evaluate("[document.querySelector('#live-quality').value,document.querySelector('#live-uc-preset').value]"), ['none', 'none']);
  await click('[data-testid=library-undo]');
  await until(() => evaluate(`document.querySelector('#live-prompt').value===${JSON.stringify(before[0])}`));
  await select('[data-testid=library-mode]', 'append');
  assert.equal(await evaluate("document.querySelector('[data-testid=library-apply-presets]').checked"), false);
  await click('[data-testid=library-apply]');
  assert.equal(await evaluate("document.querySelector('#live-prompt').value"), [before[0], 'synthetic reusable garden'].filter(v => v.length).join('\n'));
  await click('[data-testid=library-undo]');
  await click('[data-testid=library-delete]'); await waitReady();
  await until(() => evaluate("!!document.querySelector('[data-testid=library-restore]')"));
  await click('[data-testid=library-restore]'); await waitReady();
  await until(() => evaluate("!!document.querySelector('[data-testid=library-apply]')"));
  checks.push('offline library saves main text independently; explicit replace/append and undo preserve unrelated input; trash restores the preset');
  await fill('[data-testid=library-name]', 'unsaved editor');
  BrowserWindow.fromWebContents(contents).close();
  await new Promise(resolve => setTimeout(resolve, 100));
  await waitReady();
  assert.equal(BrowserWindow.fromWebContents(contents).isDestroyed(), false);
  assert.equal(await evaluate("document.querySelector('[data-testid=library-name]').value"), 'unsaved editor');
  await click('[data-testid=library-close]');
  assert.ok(await evaluate("!!document.querySelector('[data-testid=library-discard-edit]')"));
  await click('[data-testid=library-discard-edit]');
  await until(() => evaluate("!document.querySelector('[data-testid=prompt-library]')"));
  checks.push('native close preserves dirty library editor; dialog close requires explicit discard without automatic save');
  await evaluate("[...document.querySelectorAll('[data-testid=live-characters] button')].find(b=>b.textContent.includes('캐릭터 프리셋')).click()"); await waitReady();
  await fill('[data-testid=library-name]', 'Synthetic library character');
  await fill('[data-testid=library-prompt]', 'person, synthetic blue coat');
  await fill('[data-testid=library-negative]', 'hat');
  await click('[data-testid=library-save]'); await waitReady();
  await until(async () => (await evaluate('window.electron.promptLibrary.read()')).value.entries.length === initialEntries + 2);
  await click('[data-testid=library-apply]');
  await until(() => evaluate("document.querySelectorAll('[data-character-id]').length===1"));
  await close();
  const id = await evaluate("document.querySelector('[data-character-id]').dataset.characterId");
  await click(`[data-character-preset="${id}"]`); await waitReady();
  const entry = (await evaluate('window.electron.promptLibrary.read()')).value.entries.filter(p => p.kind === 'character').at(-1);
  await click(`[data-library-entry="${entry.id}"]`);
  assert.equal(await evaluate("document.querySelector('[data-testid=library-character-target]').value"), id);
  await click('[data-testid=library-apply]');
  assert.equal(await evaluate("document.querySelectorAll('[data-character-id]').length"), 1);
  checks.push('character preset adds only when explicitly requested; an existing UUID keeps its identity without duplicating cards');
  const win = BrowserWindow.fromWebContents(contents); win.setMinimumSize(360, 500); win.setSize(390, 844);
  await until(() => evaluate('innerWidth===390'));
  assert.equal(await evaluate("(()=>{const d=document.querySelector('[data-testid=prompt-library]');return d.scrollWidth<=d.clientWidth && d.getBoundingClientRect().right<=innerWidth})()"), true);
  await close();
  await click('[data-testid=open-prompt-library]'); await waitReady();
  await evaluate("document.querySelector('[data-testid=prompt-library] > details > summary').click()");
  const legacy = { version: 1, presets: { SDImageGen: [{ name: 'Legacy synthetic', frontPrompt: 'front', backPrompt: 'back', uc: 'bad', model: 'not imported' }] } };
  await evaluate(`(()=>{const input=document.querySelector('input[aria-label="기존 V3 세션 JSON"]');const data=new DataTransfer();data.items.add(new File([${JSON.stringify(JSON.stringify(legacy))}],'synthetic-legacy.json',{type:'application/json'}));input.files=data.files;input.dispatchEvent(new Event('change',{bubbles:true}));})()`);
  await until(() => evaluate("[...document.querySelectorAll('[data-testid=prompt-library] button')].some(b=>b.textContent.includes('Legacy synthetic · 초안 열기'))"));
  await evaluate("[...document.querySelectorAll('[data-testid=prompt-library] button')].find(b=>b.textContent.includes('Legacy synthetic · 초안 열기')).click()");
  assert.equal(await evaluate("document.querySelector('[data-testid=library-prompt]').value"), 'front\nback');
  await click('[data-testid=library-save]'); await waitReady();
  await until(async () => (await evaluate('window.electron.promptLibrary.read()')).value.entries.length === initialEntries + 3);
  await click('[data-testid=library-apply]');
  await until(() => evaluate("document.querySelector('[data-testid=applied-main-preset]')?.textContent.includes('Legacy synthetic')"));
  await close(); win.setSize(1400, 900); await until(() => evaluate('innerWidth===1400'));
  await click('[data-testid=project-new]');
  await until(() => evaluate("document.querySelector('[data-testid=project-confirm]')?.open"));
  await click('[data-testid=project-confirm-discard]');
  await until(() => evaluate("document.querySelectorAll('[data-character-id]').length===0"));
  assert.equal(await evaluate("!!document.querySelector('[data-testid=applied-main-preset]')"),false);
  await click('[data-testid=open-prompt-library]'); await waitReady();
  assert.equal((await evaluate('window.electron.promptLibrary.read()')).value.entries.length, initialEntries + 3);
  await close();
  assert.deepEqual((await evaluate('window.electron.projects.list()')).value.map(p => [p.id, p.revision]), beforeProjects);
  checks.push('390px library fits; legacy JSON reads text only; project switching retains the library and never writes project snapshots');
  if (process.env.SDSTUDIO_GENERATION_PHASE === 'create') {
    for (let i = 0; i < 23; i++) await click('[data-testid=add-live-character]');
    const ids = await evaluate("[...document.querySelectorAll('[data-character-id]')].map(c=>c.dataset.characterId)");
    assert.equal(ids.length, 23);
    for (const id of ids.slice(0, 22)) await fill(`[data-character-prompt="${id}"]`, 'synthetic person');
    assert.equal(await evaluate("document.querySelector('[data-testid=prepare-generation]').matches(':disabled')"), false);
    await fill(`[data-character-prompt="${ids[22]}"]`, 'synthetic last person');
    assert.ok(await evaluate("!!document.querySelector('[data-testid=character-limit-warning]')"));
    assert.equal(await evaluate("document.querySelector('[data-testid=prepare-generation]').matches(':disabled')"), true);
    await click(`[data-character-enabled="${ids[22]}"]`);
    assert.equal(await evaluate("document.querySelector('[data-testid=prepare-generation]').matches(':disabled')"), false);
    assert.equal(await evaluate(`document.querySelector('[data-character-prompt="${ids[22]}"]').value`), 'synthetic last person');
    await click('[data-testid=project-new]'); await until(() => evaluate("document.querySelector('[data-testid=project-confirm]')?.open"));
    await click('[data-testid=project-confirm-discard]'); await until(() => evaluate("document.querySelectorAll('[data-character-id]').length===0"));
    checks.push('22 ready cards plus a waiting card remain generatable; typing the23rd warns and disables Generate, disabling the card restores it without losing text');
  }
};
